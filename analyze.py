"""Run the KPI queries in queries.sql and write a Markdown + HTML report.

Usage:
    python generate_tickets.py   # creates data/tickets.db (run once)
    python analyze.py            # prints the results, writes report.md and report.html
"""
from __future__ import annotations

import html
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).parent
DB_PATH = ROOT / "data" / "tickets.db"
SQL_PATH = ROOT / "queries.sql"

TITLES = {
    "overall_kpis": "Overall KPIs",
    "sla_by_priority": "SLA compliance by priority",
    "top_categories": "Tickets by category",
    "monthly_trend": "Monthly trend",
    "busiest_hours": "Tickets by hour of day",
    "channel_performance": "Performance by channel",
    "agent_performance": "Performance by agent",
    "self_service_candidates": "Candidates for self-service / automation",
}


def load_queries(path: Path) -> dict[str, str]:
    """Split queries.sql on '-- name: <id>' markers."""
    parts = re.split(r"^-- name:\s*(\w+)\s*$", path.read_text(encoding="utf-8"), flags=re.MULTILINE)
    return {parts[i]: parts[i + 1].strip() for i in range(1, len(parts), 2)}


def run(conn: sqlite3.Connection, sql: str) -> tuple[list[str], list[tuple]]:
    cur = conn.execute(sql)
    return [d[0] for d in cur.description], cur.fetchall()


def to_markdown(cols: list[str], rows: list[tuple]) -> str:
    fmt = lambda v: "" if v is None else str(v)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def to_html_table(cols: list[str], rows: list[tuple], bar_col: str | None = None) -> str:
    """HTML table; optionally draws a horizontal bar for one numeric column."""
    max_val = max((r[cols.index(bar_col)] or 0 for r in rows), default=0) if bar_col else 0
    head = "".join(f"<th>{html.escape(c)}</th>" for c in cols)
    body = []
    for row in rows:
        cells = []
        for c, v in zip(cols, row):
            text = "" if v is None else html.escape(str(v))
            if c == bar_col and max_val:
                width = int(160 * (v or 0) / max_val)
                text = f"<span class='bar' style='width:{width}px'></span> {text}"
            cells.append(f"<td>{text}</td>")
        body.append("<tr>" + "".join(cells) + "</tr>")
    return f"<table><tr>{head}</tr>{''.join(body)}</table>"


def main() -> None:
    if not DB_PATH.exists():
        raise SystemExit("data/tickets.db not found. Run: python generate_tickets.py")

    queries = load_queries(SQL_PATH)
    md = ["# Helpdesk KPI report", "", "Synthetic dataset generated by `generate_tickets.py`.", ""]
    page = []

    with sqlite3.connect(DB_PATH) as conn:
        for name, sql in queries.items():
            cols, rows = run(conn, sql)
            title = TITLES.get(name, name)
            print(f"\n== {title} ==")
            print(to_markdown(cols, rows))
            md += [f"## {title}", "", to_markdown(cols, rows), ""]
            bar = "tickets" if "tickets" in cols and name != "overall_kpis" else None
            page.append(f"<h2>{html.escape(title)}</h2>{to_html_table(cols, rows, bar)}")

    (ROOT / "report.md").write_text("\n".join(md), encoding="utf-8")
    style = (
        "body{font-family:Segoe UI,Arial,sans-serif;margin:24px;color:#222}"
        "table{border-collapse:collapse;font-size:14px;margin-bottom:8px}"
        "th,td{border:1px solid #ccc;padding:5px 10px;text-align:left}th{background:#f3f3f3}"
        ".bar{display:inline-block;height:10px;background:#3b82f6;vertical-align:middle}"
    )
    (ROOT / "report.html").write_text(
        f"<!doctype html><html><head><meta charset='utf-8'><title>Helpdesk KPI report</title>"
        f"<style>{style}</style></head><body><h1>Helpdesk KPI report</h1>{''.join(page)}</body></html>",
        encoding="utf-8",
    )
    print("\nWrote report.md and report.html")


if __name__ == "__main__":
    main()
